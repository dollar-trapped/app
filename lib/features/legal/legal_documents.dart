void openPrivacyPolicy(BuildContext context) {
  Navigator.of(context).push(
    MaterialPageRoute<void>(
      builder: (_) => Scaffold(
        appBar: AppBar(title: const Text('개인정보처리방침')),
        body: SingleChildScrollView(
          padding: const EdgeInsets.all(24),
          child: Column(
            crossAxisAlignment: CrossAxisAlignment.start,
            children: [
              const SelectableText(
                privacyText,
                style: TextStyle(fontSize: 15, height: 1.7),
              ),
              TextButton(
                onPressed: () => _openPolicyLink(
                  context,
                  'https://policies.google.com/privacy',
                ),
                child: const Text('Google 개인정보처리방침'),
              ),
              TextButton(
                onPressed: () => _openPolicyLink(
                  context,
                  'https://developers.google.com/admob/android/privacy/play-data-disclosure',
                ),
                child: const Text('AdMob 데이터 공개 안내'),
              ),
            ],
          ),
        ),
      ),
    ),
  );
}

Future<void> _openPolicyLink(BuildContext context, String url) async {
  try {
    if (await launchUrl(Uri.parse(url), mode: LaunchMode.externalApplication)) {
      return;
    }
  } catch (_) {}
  if (!context.mounted) return;
  ScaffoldMessenger.of(
    context,
  ).showSnackBar(const SnackBar(content: Text('문서를 열지 못했습니다. 다시 시도해 주세요.')));
}

